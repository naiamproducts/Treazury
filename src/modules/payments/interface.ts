/**
 * PaymentProvider interface
 *
 * Every payment method — USDC on Arc, Santander Pay, Stripe, etc. — implements
 * this contract. The rest of the app (orders, invoices, SDK) only talks to this
 * interface, never to a concrete provider.
 *
 * Adding a new payment method = implementing this interface + registering it in
 * factory.ts. Zero other files change.
 */

import type { Order } from '../shared/types'

// ─────────────────────────────────────────────
// Core value objects
// ─────────────────────────────────────────────

export type PaymentStatus =
  | 'pending'       // Link created, no payment received
  | 'processing'    // Payment submitted, not yet final
  | 'partial'       // Some USDC received but less than expectedAmount
  | 'paid'          // Confirmed / settled (vault swept)
  | 'failed'        // Error or rejection
  | 'expired'       // Link TTL elapsed without payment
  | 'refunded'      // Full or partial refund issued

export interface PaymentCharge {
  /** Stable ID for this charge, generated by the provider. */
  id: string
  /** Provider key that created this charge (e.g. 'usdc_arc', 'santander_pay'). */
  providerKey: string
  /** Amount in human-readable decimal (e.g. "5.00"). */
  amount: string
  /** ISO 4217 currency code or stablecoin ticker ('USDC', 'VES', 'ARS'). */
  currency: string
  /** Full URL the buyer opens to complete the payment. */
  paymentUrl: string
  status: PaymentStatus
  /** ISO timestamp when this charge was created. */
  createdAt: string
  /** ISO timestamp when this charge expires, if applicable. */
  expiresAt?: string
  /** Provider-specific metadata (tx hash, order reference, etc.). */
  metadata: Record<string, string>
}

export interface PaymentReceipt {
  chargeId: string
  providerKey: string
  status: PaymentStatus
  /** Amount actually received (may differ from charged amount due to fees). */
  amountReceived: string
  currency: string
  /** Provider transaction reference (tx hash, payment ID, etc.). */
  transactionRef: string
  /** ISO timestamp of confirmed payment. */
  confirmedAt: string
  metadata: Record<string, string>
}

// ─────────────────────────────────────────────
// Provider configuration
// ─────────────────────────────────────────────

export interface CreateChargeParams {
  /** Amount in human-readable decimal. */
  amount: string
  /** Currency / stablecoin ticker. Provider validates compatibility. */
  currency: string
  /** Short description shown on the payment page (e.g. "Pedido #42"). */
  description: string
  /** Wallet or bank account address/ID that receives the funds. */
  recipientRef: string
  /** How long the link is valid, in seconds. Provider may ignore if unsupported. */
  ttlSeconds?: number
  /**
   * Display currency for the payment page (e.g. 'ARS'). The buyer can view
   * the total in this currency; settlement is ALWAYS the charge `currency`
   * (USDC). Display-only, never touches reconciliation.
   */
  displayCurrency?: string
  /** Merchant business name shown on the payment page header. */
  merchantName?: string
  /** Merchant bank details for the transfer option (all display-only). */
  bankName?: string
  bankAlias?: string
  bankAccount?: string
  /** Original order for contextual metadata. */
  order?: Order
  /** Additional provider-specific params. */
  extra?: Record<string, string>
}

export interface CheckStatusParams {
  chargeId: string
  /** Provider-specific transaction reference, if already known. */
  transactionRef?: string
}

export interface RefundParams {
  chargeId: string
  /** Amount to refund. Full refund if omitted. */
  amount?: string
  reason?: string
}

// ─────────────────────────────────────────────
// The interface every provider must implement
// ─────────────────────────────────────────────

export interface PaymentProvider {
  /**
   * Stable machine-readable key for this provider.
   * Used as discriminator in the factory and in DB records.
   * Examples: 'usdc_arc', 'usdc_base', 'santander_pay', 'stripe_link'
   */
  readonly key: string

  /** Human-readable display name shown in the UI. */
  readonly displayName: string

  /**
   * Currencies / stablecoins this provider can receive.
   * Used to validate CreateChargeParams.currency before dispatching.
   */
  readonly supportedCurrencies: readonly string[]

  /**
   * True when the provider is ready to accept real transactions.
   * A provider can be registered but disabled (e.g. missing API key).
   */
  readonly isAvailable: boolean

  /** Create a payment link / charge. */
  createCharge(params: CreateChargeParams): Promise<PaymentCharge>

  /**
   * Query the current status of a charge.
   * Implementations may poll an on-chain event, a REST API, or a webhook cache.
   */
  checkStatus(params: CheckStatusParams): Promise<PaymentReceipt | null>

  /**
   * Issue a refund for a completed charge.
   * Providers that do not support refunds should throw a descriptive error.
   */
  refund?(params: RefundParams): Promise<void>
}
